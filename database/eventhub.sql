-- Run this whole file in MySQL to create the database, tables and sample data.

DROP DATABASE IF EXISTS eventhub;
CREATE DATABASE eventhub;
USE eventhub;

-- 1. Users table (for admin login)
CREATE TABLE users (
    id INT AUTO_INCREMENT PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL
);

-- NOTE: We do NOT insert the admin user here because the password
-- must be hashed with bcrypt first. After importing this file,
-- run 'node seed.js' inside the server folder to create the
-- default admin account (see README for details).

-- 2. Events table
CREATE TABLE events (
    id INT AUTO_INCREMENT PRIMARY KEY,
    event_name VARCHAR(150) NOT NULL,
    description TEXT,
    event_date DATE NOT NULL,
    event_time TIME NOT NULL,
    location VARCHAR(150) NOT NULL
);

-- 3. Attendees table
CREATE TABLE attendees (
    id INT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    phone VARCHAR(20) NOT NULL
);

-- 4. Registrations table (many-to-many between events and attendees)
CREATE TABLE registrations (
    id INT AUTO_INCREMENT PRIMARY KEY,
    event_id INT NOT NULL,
    attendee_id INT NOT NULL,
    FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE,
    FOREIGN KEY (attendee_id) REFERENCES attendees(id) ON DELETE CASCADE,
    UNIQUE KEY unique_registration (event_id, attendee_id)
);

